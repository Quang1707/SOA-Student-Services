CREATE TABLE IF NOT EXISTS student_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id VARCHAR(20) NOT NULL,
    student_name VARCHAR(100),
    doc_type VARCHAR(100) NOT NULL,
    doc_url VARCHAR(255) NOT NULL,
    doc_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP,
    CONSTRAINT chk_student_documents_status CHECK (doc_status IN ('PENDING', 'VERIFIED'))
);

CREATE INDEX IF NOT EXISTS idx_student_documents_student_id ON student_documents (student_id);
CREATE INDEX IF NOT EXISTS idx_student_documents_status ON student_documents (doc_status);

CREATE TABLE IF NOT EXISTS student_profiles (
    student_id VARCHAR(20) PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    date_of_birth DATE NOT NULL,
    gender VARCHAR(10) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone VARCHAR(15) NOT NULL,
    major VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT chk_student_profiles_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT chk_student_profiles_status CHECK (status IN ('PENDING', 'ACTIVE', 'COMPLETED'))
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    student_id VARCHAR(20),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_users_role CHECK (role IN ('STUDENT', 'STAFF', 'ADMIN'))
);

CREATE INDEX IF NOT EXISTS idx_student_profiles_full_name ON student_profiles (LOWER(full_name));
CREATE INDEX IF NOT EXISTS idx_student_profiles_status ON student_profiles (status);
CREATE INDEX IF NOT EXISTS idx_users_student_id ON users (student_id);
